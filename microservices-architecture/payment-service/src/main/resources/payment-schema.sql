-- table name is quoted because Spring Data JDBC quotes @Table names: this keeps H2 (tests) and PostgreSQL (compose) in agreement
CREATE TABLE IF NOT EXISTS "payments" (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL UNIQUE,   -- one payment per order: makes authorize idempotent
    amount_cents BIGINT      NOT NULL,
    status       VARCHAR(20) NOT NULL
);
