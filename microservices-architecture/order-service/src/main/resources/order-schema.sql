-- table names are quoted because Spring Data JDBC quotes @Table names: this keeps H2 (tests) and PostgreSQL (compose) in agreement
CREATE TABLE IF NOT EXISTS "orders" (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(80)  NOT NULL,
    item_id     BIGINT       NOT NULL,
    quantity    INT          NOT NULL,
    address     VARCHAR(255) NOT NULL,
    total_cents BIGINT       NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    reason      VARCHAR(255),
    payment_id  BIGINT,
    courier     VARCHAR(40)
);
-- transactional outbox: written in the same transaction as the order change, relayed to other services afterwards
CREATE TABLE IF NOT EXISTS "outbox" (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind     VARCHAR(20)  NOT NULL,
    order_id BIGINT       NOT NULL,
    payload  VARCHAR(1000) NOT NULL,
    sent     BOOLEAN      NOT NULL,
    attempts INT          NOT NULL
);
