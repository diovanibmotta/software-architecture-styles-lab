-- Database layer: the only place the data model physically lives.
CREATE TABLE IF NOT EXISTS books (
    isbn         VARCHAR(20)  PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    author       VARCHAR(200) NOT NULL,
    total_copies INT          NOT NULL CHECK (total_copies >= 0)
);

CREATE TABLE IF NOT EXISTS members (
    id   VARCHAR(40)  PRIMARY KEY,
    name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS loans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn        VARCHAR(20) NOT NULL REFERENCES books (isbn),
    member_id   VARCHAR(40) NOT NULL REFERENCES members (id),
    borrowed_on DATE        NOT NULL,
    due_on      DATE        NOT NULL,
    returned_on DATE,
    fine_cents  INT
);

CREATE INDEX IF NOT EXISTS loans_active_by_member ON loans (member_id, returned_on);
CREATE INDEX IF NOT EXISTS loans_active_by_isbn ON loans (isbn, returned_on);
